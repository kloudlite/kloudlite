//go:build ignore

package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	manifestsDir := flag.String("manifests", "manifests", "directory containing generated CRD YAML manifests")
	outputPath := flag.String("output", "api/crds/assets/generated.go", "generated Go output path")
	flag.Parse()

	entries, err := os.ReadDir(*manifestsDir)
	if err != nil {
		fail("read manifests dir: %v", err)
	}

	names := make([]string, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || !(strings.HasSuffix(entry.Name(), ".yaml") || strings.HasSuffix(entry.Name(), ".yml")) {
			continue
		}
		names = append(names, entry.Name())
	}
	sort.Strings(names)
	if len(names) == 0 {
		fail("no CRD YAML manifests found in %s", *manifestsDir)
	}

	buf := &bytes.Buffer{}
	fmt.Fprintln(buf, "// Code generated by go run api/crds/assets/generate.go; DO NOT EDIT.")
	fmt.Fprintln(buf, "package assets")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "var crdYAMLDocuments = map[string]string{")
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(*manifestsDir, name))
		if err != nil {
			fail("read manifest %s: %v", name, err)
		}
		fmt.Fprintf(buf, "\t%s: %s,\n", strconv.Quote(name), strconv.Quote(string(data)))
	}
	fmt.Fprintln(buf, "}")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fail("format generated source: %v", err)
	}
	if err := os.WriteFile(*outputPath, formatted, 0644); err != nil {
		fail("write generated source: %v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
